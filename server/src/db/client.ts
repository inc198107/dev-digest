import postgres from 'postgres';
import { drizzle, type PostgresJsDatabase } from 'drizzle-orm/postgres-js';
import { schema } from './schema.js';

export type Db = PostgresJsDatabase<typeof schema>;

/** The transaction handle `db.transaction(async (tx) => …)` passes to its callback. */
export type DbTransaction = Parameters<Parameters<Db['transaction']>[0]>[0];

/**
 * Anything a repository can run queries on: the shared client or an open transaction.
 * Repositories take this so a unit of work can rebind them to a transaction.
 */
export type DbExecutor = Db | DbTransaction;

export interface DbHandle {
  db: Db;
  sql: postgres.Sql;
  close: () => Promise<void>;
}

/**
 * Create a Drizzle client over postgres-js. Used by the app (one shared handle)
 * and by the Testcontainers harness (per-test handle).
 */
export function createDb(databaseUrl: string, opts?: { max?: number }): DbHandle {
  const sql = postgres(databaseUrl, { max: opts?.max ?? 10 });
  const db = drizzle(sql, { schema });
  return {
    db,
    sql,
    close: async () => {
      await sql.end({ timeout: 5 });
    },
  };
}
